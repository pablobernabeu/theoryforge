# What the implied independencies rest on, in italics above them (API_SPEC.md
# section 11): the graph reads every omission as a claim.
.tf_CLOSED_WORLD <- paste0(
  "_Each statement follows from the causal graph as encoded, which reads every ",
  "pair of its constructs that no proposition joins as having no direct effect ",
  "on each other and no unexplained association. The statements are the ",
  "theory's commitments only if its authors meant those omissions._")

# How a rival's own propositions read a prediction's claim, beside the rival's id.
.tf_RIVAL_READS <- c(entailed = "its propositions entail the claim too",
                     contradicted = "its propositions contradict the claim",
                     undetermined = "its propositions leave the claim open")

# What an observational test of an effect claim must adjust for, or NULL.
.tf_adjustment_line <- function(rec) {
  if (is.null(rec$identified) || is.na(rec$identified)) return(NULL)
  if (!rec$identified) return("none suffices")
  set <- unlist(rec$adjustment)
  if (length(set)) paste(set, collapse = ", ") else "none needed"
}

# A line break inside a value would end the Markdown list item it is written
# into, so every run of them, with the spaces and tabs around it, becomes one
# space (API_SPEC.md section 11). Each line of the document goes through
# .tf_flat() once it is built, so that no value, an id or a date included, can
# start a line of its own, where Markdown would read a heading, a code fence or
# a YAML header in it.
.tf_flat <- function(s) gsub("[ \t]*[\r\n]+[ \t]*", " ", s, perl = TRUE)

# `s` ending in a full stop, a question mark or an exclamation mark.
.tf_sentence <- function(s) {
  s <- sub(" +$", "", s)
  if (grepl("[.?!]$", s)) s else paste0(s, ".")
}

# The claim of each item of `key` in file order, as a record, or NULL for one
# without a claim. A graph that cannot be built leaves every claim unread.
.tf_claim_records <- function(T, key, source, cycles) {
  recs <- tryCatch(Filter(function(r) r$source == source, tf_entailments(T, cycles = cycles)$claims),
                   tf_refusal = function(e) NULL)
  refused <- is.null(recs)
  its <- .tf_list(T, key)
  out <- vector("list", length(its))
  k <- 0L
  for (i in seq_along(its)) {
    cl <- .tf_read_claim(.tf_get(its[[i]], "claim"))
    if (is.null(cl)) next
    if (refused) {
      out[[i]] <- c(cl, list(verdict = "not_evaluated",
                             basis = if (cl$ok) "graph_refused" else "malformed_claim", via = list()))
    } else {
      k <- k + 1L
      out[[i]] <- recs[[k]]
    }
  }
  out
}

# For each prediction in file order, its claim and adjustment lines, or NULL
# when it states no claim (API_SPEC.md section 11).
.tf_claim_lines <- function(T, cycles) {
  lapply(.tf_claim_records(T, "predictions", "prediction", cycles), function(rec) {
    if (is.null(rec)) return(NULL)
    list(claim = .tf_claim_line(rec), adjust = .tf_adjustment_line(rec))
  })
}

# The region a prediction's bounds allow, as an interval, or NULL. An absent,
# infinite or null bound is open. A region that full validation would refuse,
# with no finite bound or a lower bound above the upper one, is not written.
.tf_region_text <- function(p) {
  b <- .tf_get(p, "bounds")
  if (!.tf_is_mapping(b)) return(NULL)
  lo <- .tf_number(.tf_get(b, "lower"))
  hi <- .tf_number(.tf_get(b, "upper"))
  if (!is.null(lo) && !is.finite(lo)) lo <- NULL
  if (!is.null(hi) && !is.finite(hi)) hi <- NULL
  if ((is.null(lo) && is.null(hi)) || (!is.null(lo) && !is.null(hi) && lo > hi)) return(NULL)
  left <- if (is.null(lo)) "(-inf" else paste0("[", .tf_plan_number(lo))
  right <- if (is.null(hi)) "inf)" else paste0(.tf_plan_number(hi), "]")
  paste0(left, ", ", right)
}

# The constructs, propositions, phenomena, assumptions, rivals and scope, in
# words.
.tf_theory_section <- function(T, cycles) {
  out <- c("", "## Theory", "", "### Constructs")
  cons <- .tf_list(T, "constructs")
  if (length(cons) == 0L) out <- c(out, "_No constructs specified._")
  for (c in cons) {
    label <- .tf_flat(.tf_str(c, "label"))
    definition <- .tf_flat(.tf_str(c, "definition"))
    line <- paste0("- ", .tf_str(c, "id"), if (.tf_ne_str(label)) paste0(" (", label, ")"), ": ",
                   if (.tf_ne_str(definition)) .tf_sentence(definition) else "No definition stated.")
    measures <- .tf_flat(.tf_str_list(.tf_get(c, "measurement")))
    if (length(measures)) line <- paste0(line, " Measures: ", paste(measures, collapse = "; "), ".")
    scope <- .tf_flat(.tf_str_list(.tf_get(c, "boundary_conditions")))
    if (length(scope)) line <- paste0(line, " Boundary conditions: ", paste(scope, collapse = "; "), ".")
    out <- c(out, line)
  }
  out <- c(out, "", "### Propositions")
  props <- .tf_list(T, "propositions")
  if (length(props) == 0L) out <- c(out, "_No propositions specified._")
  for (p in props) {
    rel <- .tf_enum_str(p, "relation", .tf_RELATION)
    frm <- .tf_str(p, "from")
    to <- .tf_str(p, "to")
    line <- paste0("- ", .tf_str(p, "id"), ": ",
                   if (nzchar(rel)) paste0(frm, " ", rel, " ", to, ".")
                   else paste0(frm, " and ", to, ", with no relation stated."))
    mechanism <- .tf_flat(.tf_str(p, "mechanism"))
    if (.tf_ne_str(mechanism)) line <- paste0(line, " Mechanism: ", .tf_sentence(mechanism))
    out <- c(out, line)
  }
  phenomena <- .tf_list(T, "phenomena")
  if (length(phenomena) > 0L) {
    out <- c(out, "", "### Phenomena to explain")
    recs <- .tf_claim_records(T, "phenomena", "phenomenon", cycles)
    for (i in seq_along(phenomena)) {
      ph <- phenomena[[i]]
      doi <- .tf_str(ph, "source_doi")
      out <- c(out, paste0("- ", .tf_str(ph, "id"), ": ", .tf_flat(.tf_str(ph, "statement")),
                           if (.tf_ne_str(doi)) paste0(" (doi: ", doi, ")")))
      if (!is.null(recs[[i]])) out <- c(out, paste0("  - Claim: ", .tf_claim_line(recs[[i]])))
    }
  }
  aux <- .tf_list(T, "auxiliary_assumptions")
  if (length(aux) > 0L) {
    out <- c(out, "", "### Auxiliary assumptions")
    for (a in aux) {
      added <- .tf_str(a, "added_for")
      kind <- if (.tf_ne_str(added)) paste("added for", added) else "core"
      out <- c(out, paste0("- ", .tf_str(a, "id"), " (", kind, "): ",
                           .tf_flat(.tf_str(a, "statement"))))
    }
  }
  alts <- .tf_list(T, "alternatives")
  if (length(alts) > 0L) {
    out <- c(out, "", "### Rival accounts")
    for (a in alts) {
      doi <- .tf_str(a, "source_doi")
      out <- c(out, paste0("- ", .tf_str(a, "id"), ": ", .tf_flat(.tf_str(a, "label")),
                           if (.tf_ne_str(doi)) paste0(" (doi: ", doi, ")")))
    }
  }
  scope <- .tf_flat(.tf_str_list(.tf_get(T, "boundary_conditions")))
  if (length(scope)) out <- c(out, "", "### Scope", paste0("- ", scope))
  out
}

# The formal-model line, when the theory declares a model of a schema type.
.tf_formal_model_line <- function(T) {
  fm <- .tf_get(T, "formal_model")
  kind <- .tf_enum(.tf_get(fm, "type"), .tf_FORMAL_MODEL_TYPE)
  if (is.null(kind)) return(character(0))
  ref <- .tf_flat(.tf_str(fm, "spec_ref"))
  paste0("- Formal model: ", kind, if (.tf_ne_str(ref)) paste0(" (", ref, ")"))
}

.tf_IMPLIED_HEADING <- paste0("## Implied conditional independencies (derived from the causal ",
                              "graph, not predictions)")

.tf_PLAN_HEADING <- "## Sampling plan (author-recorded; not scored)"

# A recorded value as the sampling plan writes it, with up to 15 significant
# digits. The plan repeats what the author recorded, so it does not round to the
# three decimals of .tf_fmt(), which would write an alpha of 0.0001 as 0.0.
# Python's format(x, ".15g") gives the same text, an exponent such as 5e-08
# included.
.tf_plan_number <- function(x) sprintf("%.15g", as.numeric(x))

# The sampling plan that prediction `p` states, or NULL when it states none. The
# test block is read leniently (API_SPEC.md section 30). A number that full
# validation would refuse reads as absent, text is read through .tf_text() and
# sided through .tf_enum(). A qualifier is written only beside the value it
# qualifies: the unit with n_planned, the scale with sesoi, and the interval and
# method with the power or decision probability.
.tf_plan <- function(p) {
  block <- .tf_get(p, "test")
  if (!.tf_is_mapping(block)) return(NULL)
  num <- function(key, ok) {
    x <- .tf_number(.tf_get(block, key))
    if (!is.null(x) && ok(x)) x else NULL
  }
  txt <- function(key) {
    s <- .tf_flat(.tf_str(block, key))
    if (.tf_ne_str(s)) s else ""
  }
  unit_interval <- function(x) x >= 0 && x <= 1

  clauses <- character(0)
  n <- num("n_planned", function(x) is.finite(x) && x == floor(x) && x >= 1)
  if (!is.null(n)) {
    unit <- txt("unit")
    clauses <- c(clauses, paste0("n = ", .tf_plan_number(n), if (nzchar(unit)) paste0(" ", unit)))
  }
  alpha <- num("alpha", function(x) x > 0 && x < 1)
  sided <- .tf_enum(.tf_get(block, "sided"), .tf_SIDED)
  level <- c(if (!is.null(alpha)) paste0("alpha ", .tf_plan_number(alpha)),
             if (!is.null(sided)) paste0(sided, "-sided"))
  if (length(level) > 0L) clauses <- c(clauses, paste(level, collapse = ", "))
  sesoi <- num("sesoi", is.finite)
  if (!is.null(sesoi)) {
    scale <- txt("sesoi_scale")
    clauses <- c(clauses, paste0("smallest effect of interest ", .tf_plan_number(sesoi),
                                 if (nzchar(scale)) paste0(" ", scale)))
  }
  power <- num("power", unit_interval)
  decision <- num("decision_probability", unit_interval)
  prob <- c(if (!is.null(power)) paste0("power ", .tf_plan_number(power)),
            if (!is.null(decision)) paste0("decision probability ", .tf_plan_number(decision)))
  if (length(prob) > 0L) {
    part <- paste(prob, collapse = ", ")
    lo <- num("power_lo", unit_interval)
    hi <- num("power_hi", unit_interval)
    if (!is.null(lo) && !is.null(hi) && lo <= hi) {
      part <- paste0(part, " [", .tf_plan_number(lo), ", ", .tf_plan_number(hi), "]")
    }
    method <- txt("method")
    clauses <- c(clauses, paste0(part, if (nzchar(method)) paste0(" (", method, ")")))
  }
  design <- txt("design_ref")
  if (nzchar(design)) clauses <- c(clauses, paste0("design: ", design))
  justification <- txt("justification")
  if (length(clauses) == 0L) return(if (nzchar(justification)) justification else NULL)
  line <- paste(clauses, collapse = "; ")
  if (nzchar(justification)) paste0(line, ". ", justification) else line
}

# The lines of the sampling-plan section, or none when no prediction states a
# plan, so a theory without a plan has no such section (API_SPEC.md section
# 30).
.tf_sampling_plan <- function(preds) {
  plans <- lapply(preds, .tf_plan)
  if (all(vapply(plans, is.null, logical(1)))) return(character(0))
  ids <- vapply(preds, function(p) .tf_str(p, "id"), character(1))
  stated <- vapply(plans, function(x) if (is.null(x)) "no sampling plan stated" else x,
                   character(1))
  c("", .tf_PLAN_HEADING, paste0("- ", ids, ": ", stated))
}

# What a test outcome found: "passed", "failed" or "no result recorded".
# tf_check() has refused a passed that is present and not a logical, so what is
# left is TRUE, FALSE or absent.
.tf_outcome_result <- function(t) {
  passed <- .tf_get(t, "passed")
  if (isTRUE(passed)) "passed" else if (isFALSE(passed)) "failed" else "no result recorded"
}

# The version line, when the version has an id, naming its parent when it has
# one.
.tf_version_line <- function(T) {
  ver <- .tf_get(T, "version")
  vid <- .tf_str(ver, "id")
  if (!.tf_ne_str(vid)) return(character(0))
  parent <- .tf_str(ver, "parent_id")
  paste0("- Version: ", vid, if (.tf_ne_str(parent)) paste0(" (parent ", parent, ")"))
}

# The assumptions whose protects names `pid`, in file order. An assumption with
# a nonempty added_for was added in answer to that prediction's anomaly, and any
# other is core, as the schema reads a null.
.tf_auxiliaries <- function(pid, aux) {
  out <- character(0)
  for (a in aux) {
    if (!(pid %in% .tf_str_list(.tf_get(a, "protects")))) next
    added <- .tf_str(a, "added_for")
    out <- c(out, paste0(.tf_str(a, "id"), " (",
                         if (.tf_ne_str(added)) paste0("added for ", added) else "core", ")"))
  }
  out
}

# Every outcome of prediction `pid`, in file order, or "untested". An outcome
# counts when its prediction_id is the string `pid`, as in the amendment
# appraisal (API_SPEC.md section 10). The registration is labelled, since a bare
# value could be read as a second date.
.tf_test_record <- function(pid, tos) {
  done <- character(0)
  for (t in tos) {
    tid <- .tf_get(t, "prediction_id")
    if (!(.tf_is_string(tid) && tid == pid)) next
    date <- .tf_str(t, "date")
    reg <- .tf_str(t, "registered")
    when <- c(if (.tf_ne_str(date)) date, if (.tf_ne_str(reg)) paste0("registered ", reg))
    done <- c(done, paste0(.tf_outcome_result(t),
                           if (length(when) > 0L) paste0(" (", paste(when, collapse = ", "), ")")))
  }
  if (length(done) == 0L) "untested" else paste0("already tested: ", paste(done, collapse = "; "))
}

# The lines of the implied-independencies section (API_SPEC.md section 11).
.tf_CYCLE <- "implications requires an acyclic causal graph; cycle found: "

.tf_implied_lines <- function(T, cycles) {
  # A refusal is what the section reports: a feedback loop under the default,
  # a repeated construct id or a relation naming an undeclared construct. Any
  # other error propagates, as it does in the Python twin, which catches only
  # the ValueError of a refusal.
  imp <- tryCatch(tf_implications(T, cycles = cycles), tf_refusal = function(e) e)
  if (inherits(imp, "error")) {
    # A loop is described for a reader, and any other reason is reported as it is.
    msg <- conditionMessage(imp)
    if (startsWith(msg, .tf_CYCLE)) {
      loop <- sub(";.*$", "", substring(msg, nchar(.tf_CYCLE) + 1L))
      return(paste0("_Not derived: the causal graph has a feedback loop, ", loop, ". With ",
                    "cycles = 'sigma', the statements are read by sigma-separation and hold if ",
                    "each loop settles to a unique equilibrium._"))
    }
    return(paste0("_Not derived: ", msg, "._"))
  }
  note <- if (isTRUE(imp$acyclic)) character(0) else
    paste0("_Read by sigma-separation, since the causal graph has a feedback loop: each ",
           "statement holds if every loop settles to a unique equilibrium._")
  stmts <- vapply(imp$implications, function(i) i$statement, character(1))
  if (length(stmts) > 0L) {
    # A code span keeps dagitty's notation whole, since Markdown reads the
    # underscores of " _||_ " as emphasis around the two bars.
    return(c(.tf_CLOSED_WORLD, note, paste0("- `", stmts, "`")))
  }
  if (length(imp$constructs) == 0L) {
    return("_None: the theory states no directed relation between constructs._")
  }
  if (length(imp$inseparable) > 0L) {
    return(c(note, "_None: no set of constructs separates any pair the theory leaves unjoined._"))
  }
  c(note, "_None: every pair of constructs in the causal graph is adjacent._")
}

#' Render the theory and hypotheses sections of a preregistration
#'
#' Returns the theory and hypotheses sections of a preregistration as a
#' deterministic Markdown string and, if \code{path} is given, writes it to that
#' file (LF, single trailing newline).
#'
#' The header gives the theory id, the version when it has an id (with its
#' parent, when one is named), the schema version, the maturity, the formal
#' model when one is declared and the status of the checklist's
#' derivation_chain item, read with the document's \code{cycles}. That line
#' states what the item checks, that the derivation references resolve and
#' that the causal graph entails every claim a prediction states and
#' contradicts no claim a phenomenon states, and answers \code{yes},
#' \code{no}, \code{not checked (feedback loop; use cycles = "sigma")} when the
#' item warns because a feedback loop leaves claims unread, or
#' \code{not applicable (no predictions)}. When the causal graph has a feedback
#' loop, the header ends with a line saying how the document reads it:
#' \code{Feedback loops: refused (a claim that names a construct on a loop or
#' downstream of one is not read)} under the default, and
#' \code{Feedback loops: read by sigma-separation (each loop is assumed to
#' settle to a unique equilibrium)} with \code{cycles = "sigma"}. A graph
#' without a loop gets no such line. A fixed line in italics then says that the
#' document was generated from the theory file, that the study design, the
#' analysis plan, the inference criteria and whatever the sampling plan leaves
#' out must be added before registration, and that the content hash identifies
#' the file and is not a time stamp.
#'
#' A theory section follows, so that the document can be read without the
#' theory file: each construct with its label, definition, measures and
#' boundary conditions, each proposition with its relation and mechanism, and,
#' when the theory has them, the phenomena it sets out to explain with what the
#' causal graph says of their claims, the auxiliary assumptions, the rival
#' accounts and the scope.
#'
#' The hypotheses section opens, when the document states any claim, with one
#' sentence naming the assumptions the verdicts on the claims rest on: the
#' graph is the causal structure, with no omitted common cause of two of its
#' constructs, each directed relation acts in its stated direction whatever
#' the other inputs, effects do not cancel exactly where a claim line ends
#' \code{unless effects cancel exactly} (faithfulness), and under
#' \code{cycles = "sigma"} each feedback loop settles to a unique equilibrium,
#' also once the intervened construct is held fixed. Each hypothesis is then
#' listed in file order with its claim type, statement,
#' prediction id and derivation, followed by the region its bounds allow, its
#' claim and what the causal graph says of it, what an observational test of an
#' effect claim must adjust for, the auxiliary assumptions that protect it
#' (`core` or `added for <id>`), the registered rivals it is declared to
#' discriminate, with how each rival's own propositions read the claim, and its
#' test record. A hypothesis that a recorded outcome has already tested reads
#' `already tested: passed (<date>, registered <where>)`, one entry per outcome,
#' and any other reads `untested`.
#'
#' When at least one prediction states a sampling plan in its \code{test}
#' block, a section headed `Sampling plan (author-recorded; not scored)`
#' follows, with one line per prediction in file order. A line gives what is
#' recorded of the planned sample, alpha and sidedness, smallest effect of
#' interest, power or decision probability, design analysis and justification.
#' A prediction without a plan reads `no sampling plan stated`. Nothing scores
#' the plan. The stated power raises no score, since more power weakens the
#' corroboration a directional prediction earns (Meehl, 1967), though it decides
#' how informative a failed test is (Lakens, 2022). A theory without a plan has
#' no such section.
#'
#' A section then lists the conditional independencies that
#' [tf_implications()] derives from the causal graph, or says why there are
#' none. They are consequences of the graph as encoded, which reads every pair
#' of constructs that no proposition joins as having no direct effect and no
#' unexplained association, so they are the theory's commitments only if its
#' authors meant those omissions, and a line in italics above them says so.
#' \code{cycles} is passed to it, to [tf_check()] and to [tf_entailments()]:
#' under the default, a graph with a feedback loop gives no independencies and
#' leaves unread the claims that name a construct on a loop or downstream of
#' one, and with \code{"sigma"} it is read by sigma-separation. The claim-form
#' severity rubric closes the document. Values are written on one line, ids and
#' dates included, so a line break inside a statement cannot end the list item
#' it belongs to or start a line of its own.
#'
#' The document is the part of a preregistration that the theory file holds. It
#' is to be completed with the study design, the analysis plan, the inference
#' criteria and whatever the sampling plan leaves out, the sections that a
#' template such as PRP-QUANT asks for (Bosnjak et al., 2022).
#'
#' It stops, as [tf_check()] does, when a test outcome's \code{passed} is
#' present and not \code{TRUE} or \code{FALSE}, or when a prediction's
#' \code{severity} is not a finite number from 0 to 1, and then writes nothing.
#'
#' @param theory A theory object (named list), such as one from [tf_read()].
#' @param path Optional destination path. When it is given, the Markdown is
#'   written with LF line endings.
#' @param cycles How a causal graph with a feedback loop is read, passed to
#'   [tf_check()], [tf_entailments()] and [tf_implications()]. \code{"refuse"}
#'   (the default) derives no independencies and leaves unread the claims that
#'   name a construct on a loop or downstream of one, and \code{"sigma"} reads
#'   the graph by sigma-separation, which assumes that each loop settles to a
#'   unique equilibrium.
#' @return The preregistration Markdown as a single string.
#' @references
#' Bosnjak, M., Fiebach, C. J., Mellor, D., Mueller, S., O'Connor, D. B.,
#'   Oswald, F. L., & Sokol, R. I. (2022). A template for preregistration of
#'   quantitative research in psychology: Report of the joint psychological
#'   societies preregistration task force. \emph{American Psychologist}, 77(4),
#'   602-615. \doi{10.1037/amp0000879}
#'
#' Lakens, D. (2022). Sample size justification. \emph{Collabra: Psychology},
#'   8(1), Article 33267. \doi{10.1525/collabra.33267}
#'
#' Meehl, P. E. (1967). Theory-testing in psychology and physics: A
#'   methodological paradox. \emph{Philosophy of Science}, 34(2), 103-115.
#'   \doi{10.1086/288135}
#' @examples
#' theory <- tf_theory("demo-1", "A demonstration theory") |>
#'   tf_add_prediction("h1", "The effect is 0.30, within 0.05.", "point",
#'                     bounds = list(lower = 0.25, upper = 0.35))
#' cat(tf_preregister(theory))
#' @export
tf_preregister <- function(theory, path = NULL, cycles = "refuse") {
  .tf_check_cycles(cycles, "preregister")
  text <- paste0(paste(.tf_document_lines(theory, cycles), collapse = "\n"), "\n")
  if (!is.null(path)) {
    .tf_write_lf(path, text)
  }
  text
}

# The lines of the preregistration, each written on one line by .tf_flat().
# `embedded` leaves out the severity section, which the dossier gives with the
# declared values beside it. The dossier passes the checklist report and the
# content hash it has computed already.
# The checklist reads the graph with the document's cycles, so that the
# derivation line and the claim lines agree.
.tf_document_lines <- function(T, cycles, embedded = FALSE, report = tf_check(T, cycles = cycles),
                               digest = tf_content_hash(T)) {
  rep <- report
  resolve <- "no"
  for (it in rep$items) {
    if (identical(it$id, "derivation_chain")) {
      resolve <- .tf_RESOLVE[[it$status]]
      break
    }
  }

  lines <- c(
    sprintf("# Preregistration: %s", .tf_flat(.tf_str(T, "title"))),
    "",
    sprintf("- Theory ID: %s", .tf_str(T, "id")),
    .tf_version_line(T),
    sprintf("- Schema version: %s", .tf_str(T, "schema_version")),
    sprintf("- Content hash: %s", digest),
    sprintf("- Maturity: %s", .tf_enum_str(T, "maturity", .tf_MATURITY)),
    .tf_formal_model_line(T),
    paste0(.tf_DERIVATION, resolve),
    .tf_feedback_line(T, cycles),
    "",
    .tf_GENERATED,
    .tf_theory_section(T, cycles),
    "",
    "## Hypotheses"
  )
  # The verdicts' assumptions open the section once when the document writes
  # any claim line, of a prediction or of a phenomenon.
  stated <- FALSE
  for (key in c("predictions", "phenomena")) {
    for (x in .tf_list(T, key)) {
      if (!is.null(.tf_read_claim(.tf_get(x, "claim")))) stated <- TRUE
    }
  }
  if (stated) lines <- c(lines, paste0("_", .tf_CLAIM_ASSUMPTIONS, "_"), "")

  preds <- .tf_list(T, "predictions")
  if (length(preds) == 0L) {
    lines <- c(lines, "_No predictions specified._")
  } else {
    aux <- .tf_list(T, "auxiliary_assumptions")
    tos <- .tf_list(T, "test_outcomes")
    alt_ids <- vapply(.tf_list(T, "alternatives"), function(a) .tf_str(a, "id"), character(1))
    claims <- .tf_claim_lines(T, cycles)
    verdicts <- .tf_prediction_verdicts(T, cycles)
    for (i in seq_along(preds)) {
      p <- preds[[i]]
      df <- .tf_str_list(.tf_get(p, "derives_from"))
      df_txt <- if (length(df) > 0L) paste(df, collapse = ", ") else "\u2014"
      pid <- .tf_str(p, "id")
      ref <- if (.tf_ne_str(pid)) paste0(pid, "; ") else ""
      lines <- c(lines, sprintf("%d. [%s] %s (%sderives from: %s)",
                                i, .tf_enum_str(p, "type", .tf_PRED_TYPE),
                                .tf_flat(.tf_str(p, "statement")), ref, df_txt))
      # Markdown nests a line under a numbered item only when it is indented by
      # the width of the number, its full stop and the space.
      pad <- strrep(" ", nchar(as.character(i)) + 2L)
      region <- .tf_region_text(p)
      if (!is.null(region)) lines <- c(lines, paste0(pad, "- Region the claim allows: ", region))
      if (!is.null(claims[[i]])) {
        lines <- c(lines, paste0(pad, "- Claim: ", claims[[i]]$claim))
        if (!is.null(claims[[i]]$adjust)) {
          lines <- c(lines, paste0(pad, "- Adjustment for an observational test: ", claims[[i]]$adjust))
        }
      }
      assumptions <- .tf_auxiliaries(pid, aux)
      if (length(assumptions) > 0L) {
        lines <- c(lines, paste0(pad, "- Auxiliary assumptions: ",
                                 paste(assumptions, collapse = ", ")))
      }
      named <- .tf_str_list(.tf_get(p, "diagnostic_vs"))
      rivals <- unique(named[named %in% alt_ids])
      if (length(rivals) > 0L) {
        reads <- if (is.null(verdicts[[i]])) list() else verdicts[[i]]$rivals
        shown <- vapply(rivals, function(d) {
          r <- reads[[d]]
          if (!is.null(r) && r %in% names(.tf_RIVAL_READS)) {
            paste0(d, " (", .tf_RIVAL_READS[[r]], ")")
          } else {
            d
          }
        }, character(1))
        lines <- c(lines, paste0(pad, "- Rivals it is declared to discriminate: ",
                                 paste(shown, collapse = ", ")))
      }
      lines <- c(lines, paste0(pad, "- Test record: ", .tf_test_record(pid, tos)))
    }
    lines <- c(lines, .tf_sampling_plan(preds))
  }

  lines <- c(lines, "", .tf_IMPLIED_HEADING, .tf_implied_lines(T, cycles))
  if (embedded) return(.tf_flat(lines))

  # The values grade the form of each claim before any data (API_SPEC section
  # 9). They say nothing of how severely a claim is tested, and the heading
  # says so.
  lines <- c(lines, "", "## Severity (pre-data rubric of claim form)")
  sev <- tf_severity(T)
  if (nrow(sev) == 0L) {
    lines <- c(lines, "_No predictions specified._")
  } else {
    for (i in seq_len(nrow(sev))) {
      lines <- c(lines, sprintf("- %s: severity %s, risk %s",
                                sev$prediction_id[i],
                                .tf_fmt(sev$computed_severity[i]),
                                .tf_fmt(sev$risk_score[i])))
    }
  }

  .tf_flat(lines)
}
