                               c("b", "causes", "a"), c("a", "increases", "y")),
                          list(c("x", "y", "positive")), constructs = c("x", "y", "a", "b"))
  expect_identical(.effects_block(theory)[1:3], c(
    .SEM_EFFECTS, .sem_claimed("h1", "x", "y", "is positive"), "effect_x_y := b_x_y"))
})

