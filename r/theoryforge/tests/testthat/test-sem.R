  # here, so the comment names one constraint that would identify it. The graph
  # is acyclic, so the effect of z on y is defined all the same.
  theory <- .claim_theory(list(c("z", "increases", "m"), c("m", "increases", "y"),
                               c("m", "associates", "y")),
