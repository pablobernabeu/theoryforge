# -- lavaan ---------------------------------------------------------------------

# The parameter table lavaan::sem() would build, with the options it sets by
# default, so that no data are needed. Its default estimator, maximum
# likelihood, takes the observed exogenous variables as given (fixed.x = TRUE),
# where lavaanify() alone would not. lavaanify() then warns when a covariance
# line names such a variable, which sem() does not.
.sem_table <- function(syntax) {
  lavaan::lavaanify(syntax, auto = TRUE, model.type = "sem", int.ov.free = TRUE,
                    int.lv.free = FALSE, auto.fix.first = TRUE, auto.fix.single = TRUE,
                    auto.var = TRUE, auto.cov.lv.x = TRUE, auto.cov.y = TRUE,
                    auto.th = TRUE, auto.delta = TRUE, auto.efa = TRUE, fixed.x = TRUE,
                    warn = FALSE)
}

test_that("lavaan frees exactly the covariances the block fixes, two degrees of freedom", {
  skip_if_not_installed("lavaan")
  syntax <- tf_compile_sem(tf_read(tf_fixture_path("modality-switching.theory.yaml")))
  lines <- strsplit(syntax, "\n", fixed = TRUE)[[1L]]
  start <- match(.SEM_ZERO, lines)
  expect_false(is.na(start))
  without <- .sem_text(lines[seq_len(start - 1L)])
  # sprintf() returns no string for no rows, where paste() would return " ~~ ".
  free_covariances <- function(pt) {
    keep <- pt$op == "~~" & pt$lhs != pt$rhs & pt$free > 0L
    sprintf("%s ~~ %s", pt$lhs[keep], pt$rhs[keep])
  }
  pt_without <- .sem_table(without)
  pt_with <- .sem_table(syntax)
  expect_identical(free_covariances(pt_without),
                   c("c_sensorimotor_experience ~~ c_lexical_familiarity",
                     "c_switch_cost ~~ c_conceptual_access"))
  expect_identical(free_covariances(pt_with), character(0))
  # Both models hold the same observed variables, so the degrees of freedom
  # differ by the number of parameters the block fixes.
  expect_identical(lavaan::lavNames(pt_with, "ov"), lavaan::lavNames(pt_without, "ov"))
  expect_identical(sum(pt_without$free > 0L) - sum(pt_with$free > 0L), 2L)
})

test_that("the block changes no covariance but those its zero lines fix", {
  # Each pair of constructs is open, a free parameter or a covariance taken
  # from the data, or closed, fixed at zero. Cutting the block off restores
  # lavaan's defaults, and against them the block may close only the pairs its
  # zero lines name. An observed moderator's covariances stay open, as the
  # free lines keep them.
  skip_if_not_installed("lavaan")
  # sprintf() returns no string for no pairs, where ifelse() would return a
  # logical vector.
  key <- function(a, b) sprintf("%s %s", pmin(a, b), pmax(a, b))
  open_pairs <- function(pt) {
    keep <- pt$op == "~~" & pt$lhs != pt$rhs & (pt$free > 0L | pt$exo == 1L)
    sort(key(pt$lhs[keep], pt$rhs[keep]))
  }
  expected <- list(observed = c("m x1", "m x2", "x1 x2"), restating = c("m x2"),
                   latent = c("x1 x2"))
  for (name in names(expected)) {
    syntax <- tf_compile_sem(.moderated_theories()[[name]])
    lines <- strsplit(syntax, "\n", fixed = TRUE)[[1L]]
    start <- match(.SEM_ZERO, lines)
    without <- .sem_text(lines[seq_len(start - 1L)])
    expect_identical(open_pairs(.sem_table(without)), expected[[name]], info = name)
    zero <- grep(" ~~ 0\\*", lines, value = TRUE)
    named <- vapply(strsplit(sub(" ~~ 0\\*", " ", zero), " ", fixed = TRUE),
                    function(p) key(p[[1L]], p[[2L]]), character(1))
    expect_identical(open_pairs(.sem_table(syntax)), setdiff(expected[[name]], named),
                     info = name)
  }
})

test_that("lavaan reads the cautions as comments and the block as covariances", {
  # Every kind of line the syntax writes is here: a single indicator (strain), a
  # moderation, a feedback loop (perf and strain) and a zero block. The comments
  # hold semicolons, which lavaan also reads as line breaks, so a parser that
  # split lines before dropping comments would take the text after them as
  # model syntax.
  theory <- .sem_theory(list(list("threat", c("t1", "t2")), list("load", c("l1", "l2")),
                             list("ident", c("i1", "i2")), list("perf", c("f1", "f2")),
                             list("strain", "s1"), list("absence", c("a1", "a2")),
                             list("turnover", c("u1", "u2"))),
                        list(c("threat", "decreases", "perf"), c("load", "increases", "perf"),
                             c("ident", "moderates", "perf"), c("perf", "causes", "strain"),
                             c("strain", "causes", "perf"), c("strain", "increases", "absence"),
                             c("strain", "increases", "turnover")))
  syntax <- tf_compile_sem(theory)
  expect_identical(syntax, .sem_text(
    .sem_header("sem"), "# Measurement model", "threat =~ t1 + t2", "load =~ l1 + l2",
    "ident =~ i1 + i2", "perf =~ f1 + f2", "strain =~ s1", "absence =~ a1 + a2",
    "turnover =~ u1 + u2", .sem_single("strain"), "# Structural model",
    "perf ~ threat", "perf ~ load", "perf ~ ident", .sem_moderation("ident", "perf"),
    "strain ~ perf", "perf ~ strain", "absence ~ strain", "turnover ~ strain",
    .sem_loop("perf", "strain"), .SEM_ZERO, "threat ~~ 0*load", "absence ~~ 0*turnover"))
  skip_if_not_installed("lavaan")
  pt <- NULL
  expect_no_warning(pt <- lavaan::lavaanify(syntax))
  user <- pt[pt$user == 1L & pt$op != "=~", ]
  expect_identical(paste(user$lhs, user$op, user$rhs),
                   c("perf ~ threat", "perf ~ load", "perf ~ ident", "strain ~ perf",
                     "perf ~ strain", "absence ~ strain", "turnover ~ strain",
                     "threat ~~ load", "absence ~~ turnover"))
  fixed <- user$op == "~~"
  expect_identical(user$free[fixed], c(0L, 0L))
  expect_identical(user$ustart[fixed], c(0, 0))
})
