# SEM/lavaan compilation (API_SPEC.md section 19): byte-identical to goldens.
# test_sem.py asserts the same outputs in Python, and the lavaan checks at the
# end are R's alone.

# The comment lines tf_compile_sem() writes, built from the texts of API_SPEC.md
# section 19 so that each test below reads as the syntax it expects.
.sem_header <- function(id) {
  c(paste0("# lavaan model generated by theoryforge for ", id),
    paste0("# Written for lavaan::sem(); indicator names are the sanitised measurement ",
           "entries and must match columns of the data."))
}
.sem_single <- function(...) {
  paste0("# Single-indicator constructs (lavaan fixes the indicator's residual variance at ",
         "zero, so each is treated as measured without error): ", paste(c(...), collapse = ", "))
}
.sem_loop <- function(...) {
  paste0("# Feedback loop among ", paste(c(...), collapse = ", "), ": a non-recursive model ",
         "may not be identified. lavaan::sem() leaves these disturbances uncorrelated, and the ",
         "order and rank conditions (Bollen, 1989) assume they may correlate, so check ",
         "identification before fitting.")
}
.sem_moderation <- function(from, to) {
  paste0("# moderation: ", from, " moderates the paths into ", to, "; add the product term ",
         "by hand (", to, " ~ <x>:", from, " for an observed predictor <x>; lavaan::sam() or ",
         "the modsem package for latent variables)")
}
.SEM_ZERO <- paste0("# Covariances the theory fixes at zero (lavaan::sem() frees them by ",
                    "default; delete this block to restore its defaults)")
.SEM_FREE <- paste0("# Covariances with a moderator, left free (once a covariance names an ",
                    "observed exogenous variable, lavaan treats the variable as random and ",
                    "fixes at zero each of its covariances that the syntax does not write, ",
                    "including one with a product term added by hand)")
.sem_text <- function(...) paste0(paste(c(...), collapse = "\n"), "\n")

# A theory from list(id, measurement) and list(from, relation, to) entries,
# the propositions numbered p1, p2 and so on in file order.
.sem_theory <- function(constructs, propositions = list(), id = "sem") {
  theory <- tf_theory(id, "SEM")
  for (con in constructs) {
    theory <- tf_add_construct(theory, con[[1L]], "Label", "A definition.",
                               measurement = con[[2L]])
  }
  for (i in seq_along(propositions)) {
    p <- propositions[[i]]
    theory <- tf_add_proposition(theory, paste0("p", i), p[[1L]], p[[3L]], p[[2L]])
  }
  theory
}
.bare <- function(...) lapply(c(...), function(x) list(x, NULL))

