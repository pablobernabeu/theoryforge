  for (cs in cases) {
    theory <- tf_read(tf_fixture_path(cs$fixture))
    got <- tf_compile_sem(theory)
    golden <- tf_read_golden(tf_expected_path(paste0(cs$id, ".sem.lavaan")))
    expect_identical(got, golden, info = cs$id)
  }
})

# -- moderation -----------------------------------------------------------------

test_that("a moderator gets its main effect, written once", {
  # sem() reads an interaction only beside its main effects, and the theory's
  # moderator had no path to the outcome. The main effect comes before the
  # comment, unless a path relation anywhere in the file writes the same line.
  constructs <- .bare("threat", "ident", "perf")
  expect_identical(
    tf_compile_sem(.sem_theory(constructs, list(c("threat", "decreases", "perf"),
                                                c("ident", "moderates", "perf")))),
    .sem_text(.sem_header("sem"), "# Measurement model", "# Structural model",
              "perf ~ threat", "perf ~ ident", .sem_moderation("ident", "perf")))
  expect_identical(
    tf_compile_sem(.sem_theory(constructs, list(c("ident", "moderates", "perf"),
                                                c("ident", "increases", "perf"),
                                                c("threat", "decreases", "perf")))),
    .sem_text(.sem_header("sem"), "# Measurement model", "# Structural model",
              .sem_moderation("ident", "perf"), "perf ~ ident", "perf ~ threat"))
  expect_identical(
    tf_compile_sem(.sem_theory(constructs, list(c("ident", "causes", "perf"),
                                                c("ident", "moderates", "perf")))),
    .sem_text(.sem_header("sem"), "# Measurement model", "# Structural model",
              "perf ~ ident", .sem_moderation("ident", "perf")))
  expect_identical(
    tf_compile_sem(.sem_theory(constructs, list(c("ident", "moderates", "perf"),
                                                c("ident", "moderates", "perf")))),
    .sem_text(.sem_header("sem"), "# Measurement model", "# Structural model",
              "perf ~ ident", .sem_moderation("ident", "perf"),
              .sem_moderation("ident", "perf")))
})

# -- covariances fixed at zero --------------------------------------------------

test_that("the zero block leaves out moderators and associated pairs", {
  # threat, prior and load are exogenous and perf and dropout terminal. The
  # moderator ident keeps lavaan's defaults, since a product term added by hand
  # changes its role, and prior and threat covary by the theory's own word. All
  # four are observed. lavaan takes the covariance of ident and load from the
  # data until threat ~~ 0*load names load, so the block writes it free. The
  # association already names prior and threat, whose covariances with ident
  # lavaan fixes at zero with or without the block.
  theory <- .sem_theory(.bare("threat", "ident", "prior", "load", "anxiety", "perf", "dropout"),
                        list(c("threat", "increases", "anxiety"),
                             c("load", "increases", "anxiety"),
                             c("anxiety", "decreases", "perf"),
                             c("anxiety", "increases", "dropout"),
                             c("prior", "increases", "perf"),
                             c("ident", "moderates", "perf"),
                             c("prior", "associates", "threat")))
  expect_identical(tf_compile_sem(theory), .sem_text(
    .sem_header("sem"), "# Measurement model", "# Structural model",
    "anxiety ~ threat", "anxiety ~ load", "perf ~ anxiety", "dropout ~ anxiety",
    "perf ~ prior", "perf ~ ident", .sem_moderation("ident", "perf"), "prior ~~ threat",
    .SEM_ZERO, "threat ~~ 0*load", "prior ~~ 0*load", "perf ~~ 0*dropout",
    .SEM_FREE, "ident ~~ load"))
})

# The theories of the next two tests share their propositions. Every construct
# is observed in the first, x1 is latent in the second and the moderator m is
# latent in the third.
.moderated_theories <- function() {
  props <- list(c("x1", "causes", "y"), c("x2", "causes", "y"), c("m", "moderates", "y"))
  list(
    observed = .sem_theory(.bare("x1", "x2", "m", "y"), props),
    restating = .sem_theory(list(list("x1", c("q1", "q2")), list("x2", NULL), list("m", NULL),
                                 list("y", NULL)), props),
    latent = .sem_theory(list(list("x1", NULL), list("x2", NULL), list("m", c("q1", "q2")),
                              list("y", NULL)), props))
}

test_that("an observed moderator keeps the covariances lavaan takes from the data", {
  # lavaan::sem() takes the covariances of observed exogenous variables from the
  # data until a covariance line names one of them. It then treats that variable
  # as random and fixes at zero each of its covariances left unwritten, so
  # x1 ~~ 0*x2 alone would also fix those of the moderator m with x1 and x2. The
  # block writes them free.
  theories <- .moderated_theories()
  structural <- c("# Structural model", "y ~ x1", "y ~ x2", "y ~ m",
                  .sem_moderation("m", "y"))
  expect_identical(tf_compile_sem(theories$observed), .sem_text(
    .sem_header("sem"), "# Measurement model", structural,
    .SEM_ZERO, "x1 ~~ 0*x2", .SEM_FREE, "x1 ~~ m", "x2 ~~ m"))
  # A line that restates a zero lavaan sets, between a latent and an observed
  # exogenous variable, names the observed one all the same.
  expect_identical(tf_compile_sem(theories$restating), .sem_text(
    .sem_header("sem"), "# Measurement model", "x1 =~ q1 + q2", structural,
    .SEM_ZERO, "x1 ~~ 0*x2", .SEM_FREE, "x2 ~~ m"))
  # lavaan frees the covariances of a latent moderator itself and fixes at zero
  # those of a latent variable with an observed one, so a latent moderator needs
  # no line.
  expect_identical(tf_compile_sem(theories$latent), .sem_text(
    .sem_header("sem"), "# Measurement model", "m =~ q1 + q2", structural,
    .SEM_ZERO, "x1 ~~ 0*x2"))
  # Nor does an observed moderator when no zero line names an observed exogenous
  # variable, since lavaan then still takes its covariances from the data.
  theory <- .sem_theory(list(list("f1", c("q1", "q2")), list("f2", c("q3", "q4")),
                             list("m", NULL), list("y", NULL)),
                        list(c("f1", "causes", "y"), c("f2", "causes", "y"),
                             c("m", "moderates", "y")))
  expect_identical(tf_compile_sem(theory), .sem_text(
    .sem_header("sem"), "# Measurement model", "f1 =~ q1 + q2", "f2 =~ q3 + q4",
    "# Structural model", "y ~ f1", "y ~ f2", "y ~ m", .sem_moderation("m", "y"),
    .SEM_ZERO, "f1 ~~ 0*f2"))
})

test_that("the zero block and the loop caution hold in a cyclic theory", {
  # The rule encodes uncorrelated disturbances, which a feedback loop does not
  # change: x1 and x2 enter the loop and y1 and y2 leave it.
  theory <- .sem_theory(.bare("x1", "x2", "a", "b", "y1", "y2"),
                        list(c("x1", "causes", "a"), c("x2", "causes", "a"),
                             c("a", "increases", "b"), c("b", "increases", "a"),
                             c("b", "causes", "y1"), c("b", "causes", "y2")))
  expect_identical(tf_compile_sem(theory), .sem_text(
    .sem_header("sem"), "# Measurement model", "# Structural model",
    "a ~ x1", "a ~ x2", "b ~ a", "a ~ b", "y1 ~ b", "y2 ~ b",
    .sem_loop("a", "b"), .SEM_ZERO, "x1 ~~ 0*x2", "y1 ~~ 0*y2"))
})

test_that("each feedback loop gets one caution, in the order of its first member", {
  # Members come in construct order, and a construct with an edge to itself is
  # a loop of one, as tf_implications() reads it.
  theory <- .sem_theory(.bare("c", "a", "b", "d", "e"),
                        list(c("a", "causes", "b"), c("b", "causes", "a"),
                             c("d", "causes", "d"), c("c", "causes", "e"),
                             c("e", "causes", "c"), c("b", "causes", "d")))
  expect_identical(tf_compile_sem(theory), .sem_text(
    .sem_header("sem"), "# Measurement model", "# Structural model",
    "b ~ a", "a ~ b", "d ~ d", "e ~ c", "c ~ e", "d ~ b",
    .sem_loop("c", "e"), .sem_loop("a", "b"), .sem_loop("d")))
})

test_that("undeclared endpoints follow the declared constructs in the zero block", {
  # tf_validate() reports an endpoint that names no construct, and the syntax
  # writes it as an observed variable. The graph takes it in claim order, after
  # every declared construct, so y and z come before u and w. A repeated id is
  # one vertex.
  theory <- .sem_theory(.bare("y", "z", "y"),
                        list(c("u", "causes", "y"), c("w", "causes", "z")))
  expect_identical(tf_compile_sem(theory), .sem_text(
    .sem_header("sem"), "# Measurement model", "# Structural model",
    "y ~ u", "z ~ w", .SEM_ZERO, "y ~~ 0*z", "u ~~ 0*w"))
})

