def test_an_effect_over_more_paths_than_the_cap_is_not_defined():
    # Ten middle constructs in each of two layers give 100 paths from x to
    # y, the cap, and a direct path makes 101.
    from theoryforge.sem import MAX_EFFECT_PATHS

    assert MAX_EFFECT_PATHS == 100
    layer1, layer2 = [f"u{i}" for i in range(10)], [f"v{i}" for i in range(10)]
    props = ([("x", "causes", u) for u in layer1]
             + [(u, "causes", v) for u in layer1 for v in layer2]
             + [(v, "causes", "y") for v in layer2])
    names = ("x", *layer1, *layer2, "y")
    block = _effects_block(_claim_theory(props, [("x", "y", "positive")], constructs=names))
    terms = block[-1].split(" := ")[1].split(" + ")
    assert len(terms) == 100
    assert terms[0] == "b_x_u0*b_u0_v0*b_v0_y" and terms[-1] == "b_x_u9*b_u9_v9*b_v9_y"
    block = _effects_block(_claim_theory(props + [("x", "causes", "y")],
                                         [("x", "y", "positive")], constructs=names))
    assert block[-1] == ("# More than 100 directed paths lead from x to y, so no parameter "
                         "is defined.")


