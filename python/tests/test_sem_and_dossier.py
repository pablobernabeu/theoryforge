"""compile_sem() and dossier() on the shipped examples."""
import theoryforge as tf


def test_compile_sem(panic_path):
    lav = tf.read(panic_path).compile_sem()
    assert "# lavaan model generated by theoryforge for panic-network-2026" in lav
    # measurement model: sanitised indicator names
    assert "c_arousal =~ heart_rate_variability + self_reported_arousal" in lav
    assert "c_perceived_threat =~ threat_appraisal_questionnaire" in lav
    # structural model: labelled directed paths (to ~ label*from)
    assert "c_perceived_threat ~ b_c_arousal_c_perceived_threat*c_arousal" in lav
    assert "c_arousal ~ b_c_perceived_threat_c_arousal*c_perceived_threat" in lav
    assert lav.endswith("\n")


def test_compile_sem_associative(weak_path):
    lav = tf.read(weak_path).compile_sem()
    # weak-demo proposition q1 is associative -> covariance
    assert "k_motivation ~~ k_drive" in lav


def test_dossier(panic_path):
    d = tf.read(panic_path).dossier()
    assert d.startswith("# theoryforge dossier: Network theory of panic disorder")
    assert ("- Checklist score: 88.0 (84.2 to 90.2 with equal weights or one weight halved or "
            "doubled)\n- Checklist coverage: 0.92\n") in d
    assert "| item | criterion | status | score | weight |" in d
    assert ("| falsifiability | At least one prediction is typed point, interval or directional; "
            "the label is the author's | pass | 1.0 | 0.15 |") in d
    assert "## Preregistration" in d
    assert "# Preregistration: Network theory of panic disorder" in d


def test_dossier_names_the_rubric_for_what_it_is(panic_path):
    # Once in the dossier's own severity list and once, a level down, in the
    # preregistration appended to it.
    d = tf.read(panic_path).dossier()
    assert d.count("\n## Severity (pre-data rubric of claim form)\n") == 1
    # The embedded preregistration leaves its own severity list out.
    assert "\n### Severity" not in d
    assert "\n## Severity\n" not in d
    assert "- pred1: severity 1.0, risk 0.9" in d


# -- what the dossier says it is (API_SPEC.md section 20) ----------------------

PREAMBLE_END = (
    "Test outcomes, evidence, registrations and declared severities are as the author recorded "
    "them. The dossier flags a recorded pass whose estimate lies outside its claimed region, a "
    "recorded failure whose estimate lies inside it, and a declared severity above the rubric, "
    "and checks nothing else that the author entered. It is not an independent audit._\n")


def test_the_dossier_names_the_checklist_score_and_says_what_it_is(panic_path):
    d = tf.read(panic_path).dossier()
    rep = tf.read(panic_path).check()
    assert ("\n- Blockers failed: 0\n\n_Generated by theoryforge from the file with the content "
            "hash above. The checklist score describes how completely the file states what "
            f"checklist {rep['checklist_version']} asks for.") in d
    assert PREAMBLE_END + "\n## Checklist\n\n| item |" in d
    assert "rigour" not in d.lower() and "/100" not in d
    assert "\n## Equivalent models (observational data)\n\n" in d


def test_the_dossier_reads_the_checklist_with_its_own_cycles(panic_path):
    # Under sigma, the loop no longer leaves pred_indep unread, so the
    # derivation chain passes, and the score is that of check(cycles="sigma").
    # A claim not checked costs nothing, so the two scores are equal and the
    # derivation line tells the readings apart.
    t = tf.read(panic_path)
    answers = {"refuse": 'not checked (feedback loop; use cycles = "sigma")', "sigma": "yes"}
    for cycles in ("refuse", "sigma"):
        rep = t.check(cycles=cycles)
        lo, hi = rep["aggregate_range"]
        d = t.dossier(cycles=cycles)
        assert (f"\n- Checklist score: {rep['aggregate_score']} ({lo} to {hi} with equal weights or "
                "one weight halved or doubled)\n") in d
        assert f"contradicts no claim a phenomenon states: {answers[cycles]}\n" in d


def test_the_dossier_flags_a_failure_whose_estimate_lies_inside_the_region(panic_path):
    # pred1 claims a value in [15, 25]. A failure with the estimate inside the
    # region, at a bound included, is noted as a pass outside it is. A failure
    # outside the region and a pass inside it carry no note.
    t = tf.read(panic_path)
    inside = "; recorded as failed, with the estimate inside that region\n"
    for est in (20, 25):
        t.data["test_outcomes"] = [{"prediction_id": "pred1", "passed": False, "estimate": est,
                                    "se": 6}]
        assert inside in t.dossier()
    t.data["test_outcomes"] = [{"prediction_id": "pred1", "passed": False, "estimate": 20, "se": 6}]
    assert "- pred1: failed; post-data severity 0.798 for [15, 25]" + inside in t.dossier()
    t.data["test_outcomes"] = [{"prediction_id": "pred1", "passed": False, "estimate": 26, "se": 2}]
    assert "post-data severity 0.309 for [15, 25]\n" in t.dossier()
    t.data["test_outcomes"] = [{"prediction_id": "pred1", "passed": True, "estimate": 20, "se": 6}]
    assert "post-data severity 0.798 for [15, 25]\n" in t.dossier()
    # An outcome without a result is not flagged either way.
    t.data["test_outcomes"] = [{"prediction_id": "pred1", "estimate": 20, "se": 6}]
    assert "- pred1: no result recorded; post-data severity 0.798 for [15, 25]\n" in t.dossier()


ASSUMPTIONS = (
    "_The verdicts on the claims assume that the graph of the propositions is the causal structure, "
    "with no omitted common cause of two of its constructs, that each directed relation acts in "
    "its stated direction whatever the other inputs (as in a linear model or a uniformly monotone "
    "one), that paths do not cancel exactly where a verdict says 'unless paths cancel exactly' "
    "(faithfulness) and, for feedback loops read by sigma-separation, that each loop settles to a "
    "unique equilibrium, also once the intervened construct is held fixed._\n")


def _offsetting(sign):
    # x raises y through m1 and lowers it through m2, so the sign of the
    # effect is open, and a claimed zero is contradicted only if the two paths
    # do not cancel exactly.
    t = (tf.new_theory("offset", "Offsetting paths")
         .add_construct("x", "X", "The cause.").add_construct("m1", "M1", "The first mediator.")
         .add_construct("m2", "M2", "The second mediator.").add_construct("y", "Y", "The outcome.")
         .add_proposition("p1", "x", "m1", "increases").add_proposition("p2", "m1", "y", "increases")
         .add_proposition("p3", "x", "m2", "increases").add_proposition("p4", "m2", "y", "decreases"))
    t.add_prediction("h1", "The paths offset.", "directional", derives_from=["p1", "p2", "p3", "p4"])
    t.data["predictions"][0]["claim"] = {"kind": "effect", "x": "x", "y": "y", "sign": sign}
    return t


def test_the_claim_lines_say_when_a_verdict_rests_on_faithfulness():
    zero = _offsetting("zero")
    line = "the effect of x on y is zero; contradicted by the causal graph, unless paths cancel exactly"
    assert "- h1 (prediction): " + line + "\n" in zero.dossier()
    assert "   - Claim: " + line + "\n" in zero.preregister()
    nonzero = _offsetting("nonzero").preregister()
    assert ("   - Claim: the effect of x on y is not zero; entailed by the causal graph through "
            "p1, p2, p3, p4, unless paths cancel exactly\n") in nonzero
    # A verdict that rests on paths of one sign says nothing of cancellation.
    assert "cancel exactly\n" not in _offsetting("positive").preregister()


def test_the_documents_name_the_assumptions_of_the_verdicts_once(modality_path):
    t = tf.read(modality_path)
    pre, dos = t.preregister(), t.dossier()
    assert pre.count(ASSUMPTIONS) == 1
    assert "\n## Hypotheses\n" + ASSUMPTIONS + "\n1. [directional]" in pre
    assert "\n## Claims and the causal graph\n\n" + ASSUMPTIONS + "\n- pred1 (prediction):" in dos
    # Once in the dossier's claims section and once in its preregistration.
    assert dos.count(ASSUMPTIONS) == 2
    # A theory that states no claim has no verdicts to qualify.
    bare = tf.new_theory("bare", "No claims")
    assert "The verdicts on the claims" not in bare.preregister() + bare.dossier()
